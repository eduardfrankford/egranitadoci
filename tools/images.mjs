#!/usr/bin/env node
/**
 * Bild-Pipeline: erzeugt aus Originalfotos responsive WebP-Varianten in public/img
 * und aktualisiert das Manifest src/app/data/images.ts.
 *
 *   npm run images -- <ordner-mit-originalen>
 *
 * Der Bild-Key ergibt sich aus dem Dateinamen (kleingeschrieben, Sonderzeichen → "-").
 * Bereits vorhandene Varianten werden übersprungen. Benötigt "sharp" (npm i -D sharp).
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { basename, extname, join } from 'node:path';

const srcDir = process.argv[2];
if (!srcDir || !existsSync(srcDir)) {
  console.error('Aufruf: npm run images -- <ordner-mit-originalen>');
  process.exit(1);
}
const sharp = (await import('sharp')).default;
const OUT = 'public/img';
const MANIFEST = 'src/app/data/images.ts';
const WIDTHS = [480, 960, 1440, 1920];
mkdirSync(OUT, { recursive: true });

const slug = (f) =>
  basename(f, extname(f))
    .replace(/-scaled$/, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');

// bestehendes Manifest einlesen
const manifest = {};
if (existsSync(MANIFEST)) {
  const re = /'([^']+)': \{ w: (\d+), h: (\d+), sizes: \[([0-9,]+)\] \}/g;
  for (const m of readFileSync(MANIFEST, 'utf8').matchAll(re))
    manifest[m[1]] = { w: +m[2], h: +m[3], sizes: m[4].split(',').map(Number) };
}

for (const file of readdirSync(srcDir).filter((f) => /\.(jpe?g|png|webp)$/i.test(f))) {
  const key = slug(file);
  const img = sharp(join(srcDir, file), { limitInputPixels: false }).rotate();
  const meta = await img.metadata();
  const widths = WIDTHS.filter((w) => w < meta.width);
  if (!widths.length || widths[widths.length - 1] < Math.min(meta.width, 1920))
    widths.push(Math.min(meta.width, 1920));
  for (const w of widths) {
    const out = join(OUT, `${key}-${w}.webp`);
    if (!existsSync(out))
      await img
        .clone()
        .resize({ width: w, withoutEnlargement: true })
        .webp({ quality: 78, effort: 4 })
        .toFile(out);
  }
  manifest[key] = { w: meta.width, h: meta.height, sizes: widths };
  console.log(`${key}: ${meta.width}x${meta.height} → ${widths.join('/')}`);
}

const lines = [
  '// Auto-generated by tools/images.mjs — do not edit by hand.',
  '// key -> intrinsic size of the original + available WebP widths in /img/.',
  'export interface ImageMeta { w: number; h: number; sizes: number[]; }',
  'export const IMAGES = {',
  ...Object.keys(manifest)
    .sort()
    .map(
      (k) =>
        `  '${k}': { w: ${manifest[k].w}, h: ${manifest[k].h}, sizes: [${manifest[k].sizes.join(',')}] },`,
    ),
  '} as const satisfies Record<string, ImageMeta>;',
  'export type ImageKey = keyof typeof IMAGES;',
  '',
];
writeFileSync(MANIFEST, lines.join('\n'));
console.log(`Manifest: ${Object.keys(manifest).length} Bilder`);
